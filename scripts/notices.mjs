// Checks that every shipped npm dependency is credited, with an accepted license and its full text.
//   node scripts/notices.mjs          fails when THIRD_PARTY_NOTICES.md or the About panel's list is out of date
//   node scripts/notices.mjs --write  rewrites both
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const NOTICES = 'THIRD_PARTY_NOTICES.md'
const CREDITS = 'src/generated/credits.json'
const MARKER = '<!-- npm dependencies: generated by scripts/notices.mjs, do not edit below this line -->'
// no license, non-commercial and source-available licenses are not on this list on purpose
const ACCEPTED = /^(MIT|ISC|0BSD|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|OFL-1\.1|MPL-2\.0|LGPL-(2\.1|3\.0)(-or-later|-only)?|GPL-(2\.0-or-later|3\.0(-or-later|-only)?)|\(MPL-2\.0 OR Apache-2\.0\))$/

// every dependency that ends up in the built app, including dependencies of dependencies
const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--long', '--json'], { encoding: 'utf8', maxBuffer: 1 << 26 }))
const found = new Map()
;(function walk(node) {
  for (const dep of Object.values(node.dependencies ?? {})) {
    if (!dep.path) continue // optional dependency that is not installed
    found.set(dep.path, dep)
    walk(dep)
  }
})(tree)

const errors = []
const deps = [...found.values()]
  .map(({ path }) => {
    const pkg = JSON.parse(readFileSync(join(path, 'package.json'), 'utf8'))
    const license = typeof pkg.license === 'string' ? pkg.license : ''
    if (!ACCEPTED.test(license)) errors.push(`${pkg.name}: license "${license || 'none'}" is not on the accepted list`)
    const file = readdirSync(path).find((name) => /^(licen[sc]e|copying)/i.test(name))
    if (!file) errors.push(`${pkg.name}: the package ships no license text`)
    const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name
    const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
    const url = pkg.homepage || repo?.replace(/^git\+/, '').replace(/\.git$/, '') || `https://www.npmjs.com/package/${pkg.name}`
    return { name: pkg.name, version: pkg.version, license, author: author ?? 'see the license text', url, text: file ? readFileSync(join(path, file), 'utf8').trim() : '' }
  })
  .sort((a, b) => a.name.localeCompare(b.name))

const section = deps
  .map((d) => `### ${d.name} ${d.version}\n\n- Author: ${d.author}\n- URL: ${d.url}\n- License: ${d.license}\n\n<details><summary>License text</summary>\n\n\`\`\`text\n${d.text}\n\`\`\`\n\n</details>`)
  .join('\n\n')
const credits = JSON.stringify(deps.map(({ name, version, license, url }) => ({ name, version, license, url })), null, 2) + '\n'

const current = readFileSync(NOTICES, 'utf8')
if (!current.includes(MARKER)) errors.push(`${NOTICES} has lost its marker line`)
const notices = current.slice(0, current.indexOf(MARKER) + MARKER.length) + '\n\n' + section + '\n'

if (process.argv.includes('--write')) {
  writeFileSync(NOTICES, notices)
  writeFileSync(CREDITS, credits)
} else {
  if (notices !== current) errors.push(`${NOTICES} does not match the installed dependencies`)
  if (credits !== readFileSync(CREDITS, 'utf8')) errors.push(`${CREDITS} does not match the installed dependencies`)
  if (errors.length) errors.push('Run "npm run licenses:write" after checking the new dependency\'s license.')
}

if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}
console.log(`${deps.length} dependencies credited in ${NOTICES}.`)
