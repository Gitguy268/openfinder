// Copies Xiao's design tokens and heading font into OpenFinder, so both apps share one source.
//   XIAO=/path/to/xiao node scripts/xiao-tokens.mjs        (default: ../xiao)
// Writes src/theme/xiao-tokens.css (without Xiao's @font-face rules: OpenFinder loads its own fonts)
// and src/theme/fonts/. The header records the SHA-256 of the source, so a check can see drift.
import { createHash } from 'node:crypto'
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const xiao = resolve(process.env.XIAO ?? '../xiao')
const source = readFileSync(join(xiao, 'shared/tokens.css'), 'utf8')
const sha = createHash('sha256').update(source).digest('hex')
const body = source
  .replace(/@font-face\s*{[^}]*}\s*/g, '')
  .replace(/\/\* Xiao design tokens[\s\S]*?\*\/\s*/, '')
writeFileSync(
  'src/theme/xiao-tokens.css',
  `/* Generated by scripts/xiao-tokens.mjs from Xiao's shared/tokens.css (MPL-2.0), sha256 ${sha}.\n * Do not edit: change Xiao's file and run npm run tokens. */\n\n${body}`,
)
copyFileSync(join(xiao, 'shared/fonts/junicode-italic-latin.woff2'), 'src/theme/fonts/junicode-italic-latin.woff2')
copyFileSync(join(xiao, 'shared/fonts/OFL-Junicode.txt'), 'src/theme/fonts/OFL-Junicode.txt')
console.log(`Xiao tokens ${sha.slice(0, 12)} copied from ${xiao}`)
